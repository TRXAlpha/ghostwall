#!/usr/bin/env python3
"""Do the shipped models beat "this name looks random"? Trivial baselines on exactly the
names public_bench.py scores the shipped models on (the same 200,000 normal names drawn
with its seed, every DGA name as listed, the current labelling), with the same metrics.

    python agents/dga_eval/baselines.py --data DIR [--out agents/dga_eval/results_baselines.md]

DIR is public_bench.py's data folder (it downloads and checks the pinned files). Needs
numpy and scikit-learn (for the AUC), and onnxruntime for the shipped TRM.
"""
from __future__ import annotations

import argparse
import csv
import math
import os
import sys
from collections import Counter

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import public_bench as pb  # noqa: E402


def entropy(label: str) -> float:
    """Shannon entropy of the characters, bits per character."""
    if not label:
        return 0.0
    n = len(label)
    return -sum(c / n * math.log2(c / n) for c in Counter(label).values())


VOWELS = set("aeiou")
BASELINES = {
    # the obvious one-liner
    "entropy (bits per char)": entropy,
    # entropy grows with length; total bits rewards long random names
    "entropy x length": lambda s: entropy(s) * len(s),
    # random strings run out of vowels and pile up digits
    "consonant/digit share x length": lambda s: (sum(ch not in VOWELS for ch in s) / max(len(s), 1)) * len(s),
}


def names(data: str):
    """The benign sample and DGA labels public_bench.py scores the shipped models on
    (its section 1, "after" labelling), drawn the same way from its seeded generator."""
    rng = np.random.default_rng(pb.SEED)
    ben_old, _, _ = pb.load(data, pb.legacy_registrable_label)
    rng.permutation(len(ben_old))                           # its first draw: the "before" run
    ben, _, _ = pb.load(data, pb.registrable_label)
    benign = [ben[i] for i in rng.permutation(len(ben))[:pb.N_BENIGN_TEST]]
    fams, labs = [], []
    with open(os.path.join(data, "dga_domains_full.csv"), newline="") as f:
        for cls, fam, dom in csv.reader(f):
            if cls == "dga":
                fams.append(fam)
                labs.append(pb.registrable_label(dom))
    return benign, labs, fams


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", required=True)
    ap.add_argument("--download", action="store_true")
    ap.add_argument("--out", default=os.path.join(HERE, "results_baselines.md"))
    a = ap.parse_args(argv)
    pb.fetch(a.data, a.download)
    benign, dga, fams = names(a.data)
    rows = []
    for name, fn in BASELINES.items():
        m = pb.metrics(np.array([fn(s) for s in benign]), np.array([fn(s) for s in dga]), fams)
        rows.append((name, m))
        print(f"{name:32s} AUC {m['auc']:.3f}  caught @1% FP {m['tpr@1%']:.1%}  @0.1% FP {m['tpr@0.1%']:.1%}", flush=True)
    shipped = pb.shipped_scorers()
    tb, td = pb.tokens(benign), pb.tokens(dga)
    pt, pl = shipped["shipped-trm"](tb), shipped["shipped-lr"](tb)
    qt, ql = shipped["shipped-trm"](td), shipped["shipped-lr"](td)
    for name, pben, pdga in (("shipped TRM", pt, qt), ("shipped LR", pl, ql),
                             ("shipped mean (what Ghostwall runs)", (pt + pl) / 2, (qt + ql) / 2)):
        m = pb.metrics(pben, pdga, fams)
        rows.append((name, m))
        print(f"{name:32s} AUC {m['auc']:.3f}  caught @1% FP {m['tpr@1%']:.1%}  @0.1% FP {m['tpr@0.1%']:.1%}", flush=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("# Baselines: do the shipped models beat \"this name looks random\"?\n\n"
                "Generated by `agents/dga_eval/baselines.py` on the public data of "
                "[results_public.md](results_public.md): the same "
                f"{len(benign):,} normal names (Tranco top 1M, V354N) and all {len(dga):,} listed DGA "
                "names (Netlab 360, 25 families), the same labelling and metrics. \"Caught\" is the "
                "share of DGA names flagged at the threshold that flags 1% (or 0.1%) of the normal names.\n\n"
                "| Scorer | AUC | Caught at 1% FP | Caught at 0.1% FP |\n|---|---|---|---|\n")
        for name, m in rows:
            f.write(f"| {name} | {m['auc']:.3f} | {m['tpr@1%']:.1%} | {m['tpr@0.1%']:.1%} |\n")
        fam_names = sorted(rows[0][1]["family@1%"])
        f.write("\nPer family, caught at 1% FP:\n\n| Family | " + " | ".join(n for n, _ in rows) + " |\n|---|"
                + "---|" * len(rows) + "\n")
        for fam in fam_names:
            f.write(f"| {fam} | " + " | ".join(f"{m['family@1%'][fam]:.0%}" for _, m in rows) + " |\n")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
