#!/usr/bin/env python3
"""How useful, and how risky, is the newly-registered-domains list (rule new_domain)?

    python agents/dga_eval/nrd_eval.py --nrd nrd_domains.bin --feed threat_feed.txt \\
        --tranco popular_domains.txt [--umbrella top-1m.csv.zip] [--out results_nrd.md]

Inputs are the files the box itself keeps (update_nrd.py, update_feed.py) plus, optionally,
Cisco Umbrella's top 1M as names real networks query. It reports:
  * the list: names per age band and memory;
  * false-positive proxy: how many Tranco top 10k / 100k / 1M registrable domains are on
    it (the rule never fires for a top-1M name, but the overlap shows how clean the list is),
    and how many Umbrella names that are NOT top-1M sites are on it (those the guard can't
    save: the rule's real exposure);
  * coverage: how many names on each threat-feed source are on it, i.e. what share of
    known-bad domains are young enough for this rule to have caught them before any list did.
It measures lists, not alerts: a name on the NRD list also has to be new to your network.
"""
from __future__ import annotations

import argparse
import datetime
import io
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
GD = os.path.join(os.path.dirname(HERE), "ghost_dns")
sys.path.insert(0, GD)
import detectors as D  # noqa: E402
from tokenizer import registrable_part  # noqa: E402


def feed_sections(path):
    """{source label: [names]} from threat_feed.txt."""
    out, label = {}, "unlabelled"
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("#@source\t"):
                parts = (line.rstrip("\n").split("\t") + [""] * 5)
                label = f"{parts[3]} ({parts[4]})" if parts[3] else parts[1]
                continue
            line = line.strip().lower()
            if line and not line.startswith("#"):
                out.setdefault(label, []).append(line)
    return out


def tranco(path, n=None):
    names = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            e = D.popular_entry(line)
            if e:
                names.append(e)
                if n and len(names) >= n:
                    break
    return names


def umbrella(path):
    with zipfile.ZipFile(path) as z:
        with z.open(z.namelist()[0]) as f:
            for line in io.TextIOWrapper(f, encoding="utf-8", errors="replace"):
                name = line.strip().split(",", 1)[-1].lower().rstrip(".")
                if name and "." in name:
                    yield name


def pct(a, b):
    return f"{100 * a / b:.2f}%" if b else "n/a"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--nrd", required=True)
    ap.add_argument("--feed", required=True)
    ap.add_argument("--tranco", required=True, help="popular_domains.txt (rank order) or a Tranco CSV")
    ap.add_argument("--umbrella", help="Cisco Umbrella top-1m.csv.zip (optional)")
    ap.add_argument("--days", type=int, default=14)
    ap.add_argument("--out", default=os.path.join(HERE, "results_nrd.md"))
    a = ap.parse_args(argv)

    import tracemalloc
    tracemalloc.start()
    nrd = D.NrdList(a.nrd, days=a.days)
    size = len(nrd)
    held = tracemalloc.get_traced_memory()[0]
    tracemalloc.stop()
    bands = [(d, len(x)) for d, x in nrd._bands]
    w = []
    w.append("# Newly registered domains: list quality and coverage\n")
    w.append(f"Generated by `agents/dga_eval/nrd_eval.py` on {datetime.date.today().isoformat()} "
             f"(list built {nrd.built}, HaGeZi NRD from Stamus Labs data). Lists change daily; "
             "these numbers hold for that day. They measure lists, not alerts: `new_domain` also needs "
             "the name to be new to your network and not a top-1M site.\n")
    w.append("## The list\n")
    w.append("| band | names |\n|---|---|")
    for d, n in bands:
        w.append(f"| {D.nrd_age_text(d)} | {n:,} |")
    w.append(f"\n{size:,} names, {held / 2**20:.1f} MiB held in ghost-dns (tracemalloc).\n")

    w.append("## False-positive proxy: popular sites on the list\n")
    top = tranco(a.tranco)
    w.append("| Tranco top | registrable domains on the NRD list |\n|---|---|")
    for n in (10_000, 100_000, 1_000_000):
        regs = {registrable_part(x) for x in top[:n]}
        hits = sum(1 for r in regs if nrd.match(r))
        w.append(f"| {n:,} | {hits:,} of {len(regs):,} ({pct(hits, len(regs))}) |")
    w.append("\nThe rule never fires for these (popular-domain guard), so this is a measure of how clean "
             "the list is, not of alerts.\n")
    if a.umbrella:
        pop = D.PopularDomains(a.tranco, top=1_000_000)
        seen, hits, regs_hit = 0, 0, set()
        for name in umbrella(a.umbrella):
            reg = registrable_part(name)
            if pop.match(reg):
                continue
            seen += 1
            if nrd.match(name):
                hits += 1
                regs_hit.add(reg)
        w.append("## Exposure: names real networks query that the guard can't save\n")
        w.append(f"Cisco Umbrella top-1M names whose registrable domain is not a Tranco top-1M site: {seen:,}. "
                 f"On the NRD list: {hits:,} names ({pct(hits, seen)}), {len(regs_hit):,} registrable domains. "
                 "Umbrella mixes every kind of traffic (including malware and trackers), so these are an "
                 "upper bound on the false alarms, not a count of them.\n")

    w.append("## Coverage: known-bad domains young enough for the rule\n")
    w.append("| threat-feed source | names | on the NRD list | share |\n|---|---|---|---|")
    total = hit_total = 0
    for label, names in feed_sections(a.feed).items():
        hits = sum(1 for x in names if nrd.match(x))
        total += len(names)
        hit_total += hits
        w.append(f"| {label} | {len(names):,} | {hits:,} | {pct(hits, len(names))} |")
    w.append(f"| all | {total:,} | {hit_total:,} | {pct(hit_total, total)} |")
    w.append(f"\nA listed name on the NRD list was registered in the last {a.days} days: a lower bound on "
             "how much of each list is young, since names stay on threat lists long after they leave the "
             "NRD window. Phishing lists are the freshest, so this is where the rule adds the most before "
             "a list catches up.\n")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(w) + "\n")
    print("\n".join(w))
    return 0


if __name__ == "__main__":
    sys.exit(main())
