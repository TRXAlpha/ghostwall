"""Evaluate the shipped models (ghostwall/models) on the frozen DRIFT test years and
write results_shipped.md: the numbers docs/ARCHITECTURE.md quotes.

    python agents/dga_eval/eval_shipped.py [--n 50000] [--years 24 25]

Needs the DRIFT token caches in data/cache (python trm/data.py builds them from
data/drift/*.parquet), numpy and onnxruntime. Scoring goes through
agents/ghost_dns/scoring.py, the same code the detector runs.

Besides all sampled names, it reports the names whose scored label (the text before the
first dot, which is all the models see) never occurs in the 2017-2019 training data:
popular benign names recur every year, and a model has an easy time with names it was
trained on.
"""
import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "agents", "ghost_dns"))

import eval_lib  # noqa: E402
from scoring import LRModel, TRMModel  # noqa: E402
from tokenizer import strip_dot  # noqa: E402

MODELS = os.path.join(ROOT, "ghostwall", "models")
THRESHOLDS = (0.6, 0.8, 0.9, 0.96, 0.995)


def label_hash(tok):
    """FNV-1a over the dot-stripped token row: equal for names the models can't tell apart."""
    t = strip_dot(np.asarray(tok).astype(np.int64)).astype(np.uint64)
    h = np.full(len(t), 1469598103934665603, dtype=np.uint64)
    with np.errstate(over="ignore"):
        for j in range(t.shape[1]):
            h ^= t[:, j]
            h *= np.uint64(1099511628211)
    return h


def train_label_hashes():
    parts = []
    for y in eval_lib.TRAIN_YEARS:
        for kind in ("benign", "dga"):
            tok = eval_lib._load(f"T{y}_{kind}", "tok")
            for i in range(0, len(tok), 2_000_000):
                parts.append(label_hash(tok[i:i + 2_000_000]))
    return np.unique(np.concatenate(parts))


def scores(lr, trm, tok):
    t = strip_dot(tok.astype(np.int64))
    p_lr = np.concatenate([lr.score_tokens(t[i:i + 8192]) for i in range(0, len(t), 8192)])
    p_trm = np.concatenate([trm.score_tokens(t[i:i + 4096]) for i in range(0, len(t), 4096)])
    return p_lr, p_trm, (p_lr + p_trm) / 2


def tpr_at(p, y, fpr):
    neg = np.sort(p[y == 0])
    thr = neg[int(np.ceil((1 - fpr) * len(neg))) - 1]
    return float((p[y == 1] > thr).mean())


def auc(p, y):
    ranks = np.empty(len(p))
    ranks[np.argsort(p, kind="mergesort")] = np.arange(1, len(p) + 1)
    pos = y == 1
    return float((ranks[pos].sum() - pos.sum() * (pos.sum() + 1) / 2) / (pos.sum() * (~pos).sum()))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=50_000, help="names per class and year")
    ap.add_argument("--years", type=int, nargs="+", default=[24, 25])
    ap.add_argument("--out", default=os.path.join(HERE, "results_shipped.md"))
    a = ap.parse_args()

    lr = LRModel(os.path.join(MODELS, "lr_coef.npy"), os.path.join(MODELS, "lr_meta.json"))
    trm = TRMModel(os.path.join(MODELS, "trm_dga_v2.onnx"))
    print("hashing training labels...", flush=True)
    seen_ref = train_label_hashes()

    md = ["# Shipped models on the frozen DRIFT test years", "",
          f"Generated by `eval_shipped.py --n {a.n}`: {a.n:,} benign + {a.n:,} DGA names per year, "
          "models trained on 2017-2019 only. \"Unseen\" = the scored label never occurs in the "
          "training years.", ""]
    for year in a.years:
        b = eval_lib.load_year(year, "benign", n_sample=a.n)
        d = eval_lib.load_year(year, "dga", n_sample=a.n)
        tok = np.concatenate([b["tokens"], d["tokens"]])
        y = np.concatenate([np.zeros(len(b["tokens"])), np.ones(len(d["tokens"]))])
        h = label_hash(tok)
        i = np.minimum(np.searchsorted(seen_ref, h), len(seen_ref) - 1)
        seen = seen_ref[i] == h
        p_lr, p_trm, p = scores(lr, trm, tok)
        md += [f"## 20{year}", "",
               f"Labels also in training: {seen[y == 0].mean():.0%} of benign, {seen[y == 1].mean():.0%} of DGA.", "",
               "| Model | Names | AUC | Caught at 1% FP | at 0.1% FP |", "|---|---|---|---|---|"]
        for name, q in (("n-gram LR", p_lr), ("TRM", p_trm), ("mean (shipped)", p)):
            for sub, m in (("all", np.ones(len(y), bool)), ("unseen", ~seen)):
                md.append(f"| {name} | {sub} | {auc(q[m], y[m]):.3f} | {tpr_at(q[m], y[m], .01):.0%} | {tpr_at(q[m], y[m], .001):.0%} |")
        md += ["", "| Mean score ≥ | Benign flagged (all / unseen) | DGA caught (all / unseen) |", "|---|---|---|"]
        for t in THRESHOLDS:
            fb = [(p[(y == 0) & m] >= t).mean() for m in (np.ones(len(y), bool), ~seen)]
            fd = [(p[(y == 1) & m] >= t).mean() for m in (np.ones(len(y), bool), ~seen)]
            md.append(f"| {t} | {fb[0]:.1%} / {fb[1]:.1%} | {fd[0]:.0%} / {fd[1]:.0%} |")
        md.append("")
        print(f"20{year} done", flush=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
