#!/usr/bin/env python3
"""Download threat-intelligence domain lists into threat_feed.txt.

    python update_feed.py [--out threat_feed.txt] [--feed URL ...] [--min 1000]

Writes atomically and refuses to replace a good feed with a bad one: if a download
fails, or the result is suspiciously small, the existing file is kept and the
exit code is non-zero. The resolver notices the changed file by itself (no restart).

The default feed is Phishing Army (about 150k domains, a few MB of RAM). Larger
lists (millions of entries) are deliberately not the default: they would cost
hundreds of MB on a Raspberry Pi.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_FEEDS = ["https://phishing.army/download/phishing_army_blocklist.txt"]
MAX_BYTES = 60 * 1024 * 1024
_HOST = re.compile(r"^[a-z0-9]([a-z0-9._-]{0,251}[a-z0-9])?$")
_IPV4 = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")


def parse_domains(text: str) -> set[str]:
    """Plain 'domain' lines or hosts-file lines ('0.0.0.0 domain'); skips comments,
    IPs, single labels and anything that is not a hostname."""
    out = set()
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip().lower()
        if not line or line.startswith("!"):
            continue
        parts = line.split()
        host = parts[-1] if len(parts) > 1 and _IPV4.match(parts[0]) else parts[0]
        host = host.rstrip(".")
        if "." not in host or _IPV4.match(host) or not _HOST.match(host):
            continue
        out.add(host)
    return out


def fetch(url: str, timeout: float = 90.0) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "ghostwall-feed/1.0"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        data = resp.read(MAX_BYTES + 1)
    if len(data) > MAX_BYTES:
        raise ValueError(f"{url}: feed larger than {MAX_BYTES // (1024 * 1024)} MB, refusing")
    return data.decode("utf-8", "replace")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="update the Ghostwall threat feed")
    ap.add_argument("--out", default=os.path.join(HERE, "threat_feed.txt"))
    ap.add_argument("--feed", action="append", help="feed URL (repeatable)")
    ap.add_argument("--min", type=int, default=1000, help="refuse to write fewer domains than this")
    args = ap.parse_args(argv)

    domains: set[str] = set()
    for url in args.feed or DEFAULT_FEEDS:
        try:
            got = parse_domains(fetch(url))
        except Exception as exc:  # noqa: BLE001
            print(f"[feed] FAILED {url}: {exc}; keeping existing feed", file=sys.stderr)
            return 1
        print(f"[feed] {url}: {len(got)} domains")
        domains |= got

    if len(domains) < args.min:
        print(f"[feed] only {len(domains)} domains (< {args.min}); keeping existing feed", file=sys.stderr)
        return 1

    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(os.path.abspath(args.out)), prefix=".feed-")
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(f"# Ghostwall threat feed, {len(domains)} domains. Generated by update_feed.py; do not edit.\n")
        f.write("\n".join(sorted(domains)) + "\n")
    os.chmod(tmp, 0o644)  # mkstemp creates 0600; the feed is public data
    os.replace(tmp, args.out)
    print(f"[feed] wrote {len(domains)} domains to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
